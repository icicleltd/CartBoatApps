"""Regenerates lib/core/theme/phosphor_icons.g.dart.

Scans lib/ for PhosphorIcons<Style>.<name> usages and resolves code points
from the phosphor_flutter sources in the pub cache (the package itself can't
be compiled on Flutter >= 3.44 because it extends the now-final IconData).

Usage: python tool/gen_icons.py <path-to-phosphor_flutter-2.1.0>
"""
import glob
import os
import re
import sys

pc = sys.argv[1]
used = {}
for f in glob.glob('lib/**/*.dart', recursive=True):
    if f.endswith('phosphor_icons.g.dart'):
        continue
    s = open(f, encoding='utf-8').read()
    for style, name in re.findall(r'PhosphorIcons(Regular|Bold|Fill|Duotone)\.(\w+)', s):
        used.setdefault(style, set()).add(name)

files = {
    'Regular': 'phosphor_icons_regular.dart',
    'Bold': 'phosphor_icons_bold.dart',
    'Fill': 'phosphor_icons_fill.dart',
    'Duotone': 'phosphor_icons_duotone.dart',
}
out = [
    '// GENERATED by tool/gen_icons.py from Phosphor Icons (MIT, phosphoricons.com).',
    '// Only the glyphs the app uses are listed; regenerate after adding icons.',
    '',
    "import 'package:flutter/widgets.dart';",
    '',
]
secondary = {}
missing = []
for style in ['Regular', 'Bold', 'Fill', 'Duotone']:
    if style not in used:
        continue
    s = open(os.path.join(pc, 'lib', 'src', files[style]), encoding='utf-8').read()
    out.append(f'abstract final class PhosphorIcons{style} {{')
    for name in sorted(used[style]):
        if style == 'Duotone':
            m = re.search(r'static const %s = PhosphorDuotoneIconData\(\s*(0x[0-9a-fA-F]+),\s*PhosphorIconData\((0x[0-9a-fA-F]+)' % name, s)
            if not m:
                missing.append((style, name))
                continue
            out.append(f"  static const {name} = IconData({m.group(1)}, fontFamily: 'PhosphorDuotone');")
            secondary[m.group(1)] = m.group(2)
        else:
            m = re.search(r'static const %s = PhosphorFlatIconData\(\s*(0x[0-9a-fA-F]+)' % name, s)
            if not m:
                missing.append((style, name))
                continue
            out.append(f"  static const {name} = IconData({m.group(1)}, fontFamily: 'Phosphor{style}');")
    out.append('}')
    out.append('')
out.append('/// Secondary (tinted) layer for each duotone glyph, keyed by primary code point.')
out.append('const phosphorDuotoneSecondary = <int, IconData>{')
for k, v in secondary.items():
    out.append(f"  {k}: IconData({v}, fontFamily: 'PhosphorDuotone'),")
out.append('};')
open('lib/core/theme/phosphor_icons.g.dart', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print({k: len(v) for k, v in used.items()}, 'missing:', missing)
